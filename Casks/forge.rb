  sha256 "df1198bb6ce0196731581d56ef1fa46e08dfefdcb62ff82d4f3c5e423bd9fe6c"

  url "https://github.com/DiegoAndres717/forge/releases/download/v#{version}/Forge-#{version}.dmg"
